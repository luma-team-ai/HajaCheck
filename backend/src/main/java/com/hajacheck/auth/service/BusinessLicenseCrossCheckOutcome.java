package com.hajacheck.auth.service;

/**
 * 업로드된 사업자등록증(OCR) ↔ 가입 폼에 입력된 사업자등록번호 대조 판정(#1469 / HAJA-650).
 *
 * <p><b>fail-open이 이 판정 체계의 기본값이다</b> — 국세청 진위확인(#596)과 같은 결로, OCR 오탐
 * (그림자·기울어진 스캔·저해상도)으로 정상 사용자를 차단하는 손해가 위조 조합 하나를 놓치는 손해보다
 * 크다고 판단했다(위조는 국세청 진위확인이 1차로 거른다).
 *
 * <p><b>fail-closed 는 "좁은 축"에만 둔다</b>(2026-08-04 2차 리뷰에서 방향 정정). 한때 전역 캡 소진
 * ({@link #RATE_LIMITED})도 429 로 막았으나 <b>되돌렸다</b> — 전역 축은 <i>모든 가입자</i>가 공유하므로,
 * 공격자가 캡을 태우는 것만으로 그날 기업 가입을 전면 정지시키는 <b>DoS 킬스위치</b>가 된다
 * ({@code AuthProperties.PasswordResetRateLimit} 이 같은 이유로 전역 상한을 크게 잡아둔 것과 같은 논리).
 * "관측 가능한 가용성 저하 ≪ 무증상 보안 우회"라는 판단은 <b>그 저하를 공격자가 임의로 유발할 수 없을
 * 때만</b> 성립한다.
 *
 * <p>반면 사업자번호 축({@link #BRN_ATTEMPT_EXCEEDED})·래스터화 동시 상한({@link #RASTERIZE_BUSY})은
 * <b>자기제한적</b>이다 — 전자는 그 번호로 시도하는 주체에게만, 후자는 PDF 업로드 경로에만 작용하고
 * 지속 시간도 초 단위다. 그래서 이 둘만 429 로 막는다.
 *
 * <p>따라서 아래 8종 중 {@link #MISMATCH}·{@link #BRN_ATTEMPT_EXCEEDED}·{@link #RASTERIZE_BUSY} 가
 * 차단 사유이고 나머지 5종은 통과다.
 * 다만 통과 사유가 무엇이었는지는 {@code companies.business_registration_ocr_raw.licenseOcrOutcome}
 * 에 영속된다 — 그래야 배포 후에 "대조가 실제로 수행된 회사"와 "대조를 못 한 채 승인된 회사"를
 * 구분해 재구성할 수 있다(#1324 자동승인이라 사람 심사 기록이 따로 없다).
 *
 * <p>⚠️ {@code ntsOutcome} 과 마찬가지로 이 값도 <b>과거 데이터에는 키 자체가 없다</b>(#1469 이전
 * 가입분). 감사 쿼리에서 {@code valueOf()} 파싱을 전제하지 말 것.
 */
public enum BusinessLicenseCrossCheckOutcome {

    /** OCR이 읽은 사업자등록번호(숫자 10자리) == 입력값. 대조가 실제로 성립했고 일치한 유일한 경우. */
    MATCH,

    /**
     * OCR이 읽은 사업자등록번호 != 입력값 — 이 게이트의 <b>본체 차단 사유</b>. 남의 사업자등록증을
     * 올리고 실재하는 제3의 회사 정보를 수기로 입력하는 우회를 여기서 막는다.
     */
    MISMATCH,

    /**
     * 같은 사업자등록번호로 대조를 <b>반복 실패</b>해 시도 한도를 넘긴 경우 — AI 호출 없이 즉시 차단한다.
     *
     * <p><b>왜 필요한가</b>: {@link #MISMATCH} 로 차단되면 회사·유저 행이 생기지 않으므로 이메일·
     * 사업자번호 중복검사가 영원히 통과하고 <b>같은 요청을 무한히 반복</b>할 수 있다. 시도마다 전역 캡을
     * 태우므로, 이 축이 없으면 "차단당한 시도들이 스스로 게이트의 연료를 태워" 전역 캡을 소진시킨다
     * (2026-08-04 리뷰 P1). 좁은 축을 먼저 걸어 <b>한 사업자번호가 전역 예산을 갉아먹지 못하게</b> 한다.
     *
     * <p><b>응답은 429 중립 문구</b>({@code AUTH_BUSINESS_LICENSE_CHECK_UNAVAILABLE})다 —
     * {@link #MISMATCH} 와 같은 400 으로 합치자는 초안을 <b>되돌렸다</b>(2차 리뷰). ①정보 은닉 이득이
     * 사실상 0 이다: 이 판정은 AI 호출 없이 수 ms 에 돌아오고 진짜 {@code MISMATCH} 는 OCR 왕복(수 초)이라
     * <b>응답 시간만으로 구분</b>된다. ②반면 정상 사용자 피해는 크다: AI 장애 중 3번 시도하면 전부
     * {@link #OCR_FAILED} 로 카운터가 차고, 그다음부터 "등록증 번호가 입력값과 다릅니다"라는 <b>사실과
     * 다른 안내</b>를 받는다(흐린 스캔을 고쳐 다시 올리는 건 첫 가입자의 가장 흔한 경로다).
     *
     * <p>그 오안내를 더 줄이기 위해 <b>{@link #OCR_FAILED}(우리 쪽 장애)일 때는 이 카운터를 되돌린다</b>.
     * {@link #OCR_NO_BRN} 까지 되돌리지는 않는다 — 빈 이미지로 무한 시도하는 세탁 경로가 열린다.
     */
    BRN_ATTEMPT_EXCEEDED,

    /**
     * PDF 래스터화 <b>동시 상한</b> 포화로 대조를 수행하지 못한 경우 — 이 파일의 문제가 아니라 용량 문제다.
     *
     * <p>{@link #RATE_LIMITED}(전역 캡, fail-open)와 달리 <b>429 로 막는다</b>. 통과시키면 공격자가 무거운
     * PDF 로 렌더 슬롯을 점유해 놓고 위조 PDF 를 통과시키는 <b>직접적인 게이트 우회</b>가 되기 때문이다.
     * 반대로 막았을 때의 피해는 <b>PDF 업로드 경로에 한정</b>되고(사진 업로드는 무영향, 그리고 그쪽이
     * 다수 경로다) 지속 시간도 렌더 시간(초 단위)만큼이라, 전역 캡 fail-closed 가 만들었던 "그날 가입
     * 전면 정지"와는 피해 규모가 다르다.
     */
    RASTERIZE_BUSY,

    /**
     * OCR 응답에 사업자등록번호가 없거나(null/공백) 숫자만 남겼을 때 10자리가 아님 = 신뢰할 수 없는
     * 인식 결과. 대조 대상이 없으므로 통과시킨다(불완전 인식으로 정상 가입을 막지 않는다).
     *
     * <p><b>입력값</b>이 숫자 10자리가 아닌 경우도 같은 값으로 돌려준다 — 대조의 기준값 자체를 신뢰할 수
     * 없으면 "다르다"고 단정할 근거도 없기 때문이다. 지금은 DTO {@code @Pattern} 이 형식을 보장하지만,
     * <b>차단형 게이트가 상위 검증에 암묵적으로 의존하면</b> 그 검증이 느슨해지는 순간 정상 사용자를
     * 차단하게 된다(리뷰 P3) — OCR 측 자릿수 검사와 대칭을 맞춘다.
     */
    OCR_NO_BRN,

    /**
     * AI 서버 호출 실패(연결 불가·5xx·응답 형식 불량)·OCR/LLM 거부({@code ApiResponse.fail})·파일 읽기 실패.
     * 외부 장애가 가입 자체를 막으면 안 되므로 통과(국세청 진위확인의 {@code SKIPPED}와 같은 취급).
     */
    OCR_FAILED,

    /**
     * OCR로 다룰 수 없는 업로드라 <b>AI 서버를 호출조차 하지 않은</b> 경우 — <b>실제 바이트</b>가
     * JPEG·PNG·PDF 중 어느 것도 아니거나, 픽셀폭탄, 용량 초과, 파일 부재, PDF 래스터화 불가
     * (암호화·손상·페이지 0).
     *
     * <p>⚠️ 판정 근거는 <b>언제나 매직바이트</b>다 — 선언 {@code Content-Type} 을 믿고 분기하면 파트
     * 헤더 한 줄을 바꾸는 것만으로 게이트를 통째로 건너뛸 수 있다(2026-08-04 리뷰 P1). 그래서 PDF 도
     * 첫 페이지를 래스터화해 같은 OCR 경로에 태운다 — "PDF는 대조 불가"라는 예외 구멍 자체를 없앤다.
     *
     * <p>이 상태에서 예외를 던지지는 않는다 — 파일의 <b>진짜</b> 적합성 판정은 뒤이어 실행되는
     * {@code FileStorageService.store} 가 {@code FILE_*} 코드로 내린다(그쪽도 매직바이트를 검증한다).
     * 대조 단계가 먼저 던지면 회원가입 파일 정책을 이 게이트가 임의로 좁히게 된다.
     */
    SKIPPED_UNSUPPORTED_TYPE,

    /**
     * 대조 전용 <b>전역</b> rate-limit(분당/일일) 소진 — AI 과금·CPU 방어선에 걸려 대조를 수행하지 못한 경우.
     * <b>fail-open 통과</b>이며, 소진 사실은 {@code log.error} 로 경보한다.
     *
     * <p>⚠️ <b>이 값을 429 차단으로 바꾸려는 시도를 되돌렸다</b>(2026-08-04 2차 리뷰). 전역 축은 모든
     * 가입자가 공유하므로, 막는 순간 <b>공격자가 캡을 태우는 것만으로 그날 기업 가입을 전면 정지</b>시킬
     * 수 있다 — {@code RateLimiter#reset} javadoc 이 경고하는 "무인증 경로에서의 카운터 조작"과
     * {@code AuthProperties.PasswordResetRateLimit} 의 "전역 상한 = DoS 킬스위치" 경고가 정확히 이 상황을
     * 가리킨다. fail-closed 는 <b>공격자 자신에게만 작용하는 좁은 축</b>({@link #BRN_ATTEMPT_EXCEEDED})과
     * <b>피해가 국소적인 축</b>({@link #RASTERIZE_BUSY})에만 둔다.
     *
     * <p>캡을 공개 프리필과 분리한 이유는 별개로 유효하다 — 공유하면 비로그인 프리필 API 반복 호출만으로
     * 가입 경로의 대조 예산을 태울 수 있다.
     */
    RATE_LIMITED
}
