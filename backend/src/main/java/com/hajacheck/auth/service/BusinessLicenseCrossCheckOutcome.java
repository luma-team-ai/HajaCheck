package com.hajacheck.auth.service;

/**
 * 업로드된 사업자등록증(OCR) ↔ 가입 폼에 입력된 사업자등록번호 대조 판정(#1469 / HAJA-650).
 *
 * <p><b>fail-open이 이 판정 체계의 핵심 원칙이다</b> — 국세청 진위확인(#596)과 같은 결로,
 * <i>확정적으로 다를 때({@link #MISMATCH})만</i> 가입을 막고 "판정 불가"는 전부 통과시킨다.
 * OCR 오탐(그림자·기울어진 스캔·저해상도)으로 정상 사용자를 차단하는 손해가, 위조 조합 하나를
 * 놓치는 손해보다 크다고 판단했다(위조는 국세청 진위확인이 1차로 거른다).
 *
 * <p>따라서 아래 6종 중 {@link #MISMATCH} 하나만 차단 사유이고 나머지 5종은 모두 통과다.
 * 다만 통과 사유가 무엇이었는지는 {@code companies.business_registration_ocr_raw.licenseOcrOutcome}
 * 에 영속된다 — 그래야 배포 후에 "대조가 실제로 수행된 회사"와 "대조를 못 한 채 승인된 회사"를
 * 구분해 재구성할 수 있다(#1324 자동승인이라 사람 심사 기록이 따로 없다).
 *
 * <p>⚠️ {@code ntsOutcome} 과 마찬가지로 이 값도 <b>과거 데이터에는 키 자체가 없다</b>(#1469 이전
 * 가입분). 감사 쿼리에서 {@code valueOf()} 파싱을 전제하지 말 것.
 */
public enum BusinessLicenseCrossCheckOutcome {

    /** OCR이 읽은 사업자등록번호(숫자 10자리) == 입력값. 대조가 실제로 성립했고 일치한 유일한 경우. */
    MATCH,

    /**
     * OCR이 읽은 사업자등록번호 != 입력값 — <b>유일한 차단 사유</b>. 남의 사업자등록증을 올리고
     * 실재하는 제3의 회사 정보를 수기로 입력하는 우회를 여기서 막는다.
     */
    MISMATCH,

    /**
     * OCR 응답에 사업자등록번호가 없거나(null/공백) 숫자만 남겼을 때 10자리가 아님 = 신뢰할 수 없는
     * 인식 결과. 대조 대상이 없으므로 통과시킨다(불완전 인식으로 정상 가입을 막지 않는다).
     */
    OCR_NO_BRN,

    /**
     * AI 서버 호출 실패(연결 불가·5xx·응답 형식 불량)·OCR/LLM 거부({@code ApiResponse.fail})·파일 읽기 실패.
     * 외부 장애가 가입 자체를 막으면 안 되므로 통과(국세청 진위확인의 {@code SKIPPED}와 같은 취급).
     */
    OCR_FAILED,

    /**
     * OCR로 다룰 수 없는 업로드라 <b>AI 서버를 호출조차 하지 않은</b> 경우 — PDF 등 이미지 2종
     * (image/jpeg·image/png) 외 형식, 매직바이트 불일치, 픽셀폭탄, 용량 초과, 파일 부재.
     *
     * <p>이 사전 검사들이 실패해도 여기서 예외를 던지지 않는다 — 파일의 <b>진짜</b> 적합성 판정은
     * 뒤이어 실행되는 {@code FileStorageService.store} 가 {@code FILE_*} 코드로 내린다. 대조 단계가
     * 먼저 던지면 회원가입 파일 정책(PDF 허용)을 이 게이트가 임의로 좁히게 된다.
     */
    SKIPPED_UNSUPPORTED_TYPE,

    /**
     * 대조 전용 rate-limit(분당/일일) 소진 — AI 서버·LLM 과금 방어선에 걸려 호출을 건너뛴 경우.
     *
     * <p>⚠️ 이 값이 로그·DB에 늘어난다는 건 <b>게이트가 조용히 꺼져 있었다</b>는 뜻이다
     * (fail-open이라 가입은 그대로 통과했다). 대조 캡을 공개 프리필 캡과 분리한 이유가 바로 이것 —
     * 캡을 공유하면 비로그인 프리필 API 반복 호출만으로 이 게이트를 통째로 무력화할 수 있다.
     */
    RATE_LIMITED
}
